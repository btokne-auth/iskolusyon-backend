-- ---------------------------------------------------------------------
-- 1. Role flag on admin_accounts.
--    admin.html's nav gates "Admin Accounts" and "System & Activity" behind
--    a Super Admin role that doesn't exist in the real schema yet. Default
--    TRUE so your existing seeded account (and this whole migration) is a
--    no-op for anyone already logged in — nothing breaks before a demo.
-- ---------------------------------------------------------------------
ALTER TABLE admin_accounts
  ADD COLUMN IF NOT EXISTS is_super_admin boolean NOT NULL DEFAULT true;

-- ---------------------------------------------------------------------
-- 2. Announcements (backs the new Communications panel).
--    Minimal, real, no RLS — same server-side-service-role-only pattern as
--    every other table in this project. `category` matches the field Ivy's
--    Patch 3 admin.html draft (PR #8, still unmerged as of last check) adds
--    to her Quill-editor version; kept here as a plain text field so this
--    doesn't depend on that PR landing.
-- ---------------------------------------------------------------------
create table if not exists announcements (
  id bigint generated by default as identity primary key,
  author text not null,
  title text not null,
  body text not null,
  category text,
  created_at timestamptz not null default now()
);
