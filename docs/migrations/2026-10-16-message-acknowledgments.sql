-- Oct 16 2026: read acknowledgment for portal announcements and messages
-- (client recommendation, Registrar interview of Oct 15: applicants said
-- they never read a notice, and CCC had no proof that they did).
--
-- 1. announcements.requires_ack: posts made from now on ask the applicant
--    to confirm they read them. Every post that already exists is set to
--    false, so current applicants don't get a pop-up for old notices.
--
-- 2. message_acknowledgments: one row per applicant per post, written when
--    the applicant ticks "I have read and understood this message" and
--    clicks Confirm. Kept even if the applicant's application is later
--    archived; removed only if the post itself is deleted.
--
-- Row Level Security is on with no policies, like every other table: only
-- the server (service role) can read or write it.
--
-- Safe to run again.

-- Added with default false so every existing row gets false, then the
-- default switches to true for new posts. Running this again changes nothing.
alter table public.announcements
  add column if not exists requires_ack boolean not null default false;
alter table public.announcements
  alter column requires_ack set default true;

create table if not exists public.message_acknowledgments (
  id bigint generated by default as identity primary key,
  announcement_id bigint not null references public.announcements(id) on delete cascade,
  applicant_user_id uuid not null references public.applicant_accounts(id),
  acknowledged_at timestamptz not null default now(),
  unique (announcement_id, applicant_user_id)
);

create index if not exists message_acknowledgments_announcement_idx
  on public.message_acknowledgments (announcement_id);

alter table public.message_acknowledgments enable row level security;
