-- Oct 6 2026: Scholarship Matching & Filtering Module, last pieces.
--
-- 1. Qualification Conflict Detection (Member Roles; manuscript p. 10:
--    "flags qualification conflicts"). Conflicts are worked out on the fly
--    from the profile and what OCR read from the documents; this table only
--    remembers which ones an admin has checked. The key holds the values
--    compared, so a conflict whose values change shows up again.
-- 2. Admitted program (Appendix J p. 96, rule b): when an applicant doesn't
--    reach the passing grade of their priority program, CCC re-evaluates them
--    for another program based on the exam score. NULL = the 1st choice.
-- 3. Lowest Senior High grade in Mathematics and Science subjects
--    (Appendix J p. 96, rule a): BSEd Mathematics and BSEd Science need 85
--    or higher in every SHS Mathematics and Science subject.
--
-- Run this in Supabase (SQL Editor) BEFORE pushing the code that uses it.

create table if not exists public.conflict_checks (
  id bigint generated by default as identity primary key,
  application_id bigint not null references public.applications(id) on delete cascade,
  conflict_key text not null,
  note text,
  checked_by text,
  checked_at timestamptz not null default now(),
  unique (application_id, conflict_key)
);

alter table public.conflict_checks enable row level security;

alter table public.applications
  add column if not exists admitted_program text,
  add column if not exists admitted_program_set_by text,
  add column if not exists admitted_program_set_at timestamptz,
  add column if not exists shs_math_science_lowest numeric;

comment on column public.applications.admitted_program is
  'Program the applicant was accepted in after re-evaluation (Appendix J p. 96, rule b). NULL means the 1st choice.';
comment on column public.applications.shs_math_science_lowest is
  'Lowest Senior High grade in Mathematics and Science subjects. Asked only when a choice is BSEd Mathematics or BSEd Science (Appendix J p. 96, rule a: 85 or higher).';
