-- 1. Account roles.
--    is_super_admin stays the source of truth for Super Admins (old code and
--    scripts/seed-admin-account.mjs still set it). `role` adds the two
--    limited roles: 'registrar' (Office of the Registrar, posts allowances)
--    and 'lgu' (view-only, sees CHED Form 3 reports released to the LGU,
--    only between access_from and access_until).
alter table public.admin_accounts
  add column if not exists role text,
  add column if not exists access_from date,
  add column if not exists access_until date;

update public.admin_accounts
  set role = case when is_super_admin then 'super_admin' else 'admin' end
  where role is null;

alter table public.admin_accounts alter column role set default 'admin';
alter table public.admin_accounts alter column role set not null;

alter table public.admin_accounts drop constraint if exists admin_accounts_role_check;
alter table public.admin_accounts add constraint admin_accounts_role_check
  check (role in ('super_admin', 'admin', 'registrar', 'lgu'));

-- A limited role can never also be a Super Admin.
alter table public.admin_accounts drop constraint if exists admin_accounts_limited_not_super;
alter table public.admin_accounts add constraint admin_accounts_limited_not_super
  check (not (is_super_admin and role in ('registrar', 'lgu')));

-- LGU accounts must have an access window; the end can't be before the start.
alter table public.admin_accounts drop constraint if exists admin_accounts_lgu_access_check;
alter table public.admin_accounts add constraint admin_accounts_lgu_access_check
  check (
    role <> 'lgu'
    or (access_from is not null and access_until is not null and access_until >= access_from)
  );

-- 2. Allowance posts (Office of the Registrar). A removed post is kept with
--    removed_at/removed_by for the record; the scholar no longer sees it.
create table if not exists public.allowance_posts (
  id bigint generated by default as identity primary key,
  application_id bigint not null references public.applications(id) on delete cascade,
  distribution_date date not null,
  allowance_type text not null check (allowance_type in ('Wi-Fi', 'Other')),
  description text,
  posted_by text not null,
  posted_by_email text,
  posted_at timestamptz not null default now(),
  removed_at timestamptz,
  removed_by text,
  constraint allowance_posts_other_needs_description
    check (allowance_type <> 'Other' or (description is not null and length(trim(description)) > 0))
);
create index if not exists allowance_posts_application_idx on public.allowance_posts (application_id);
alter table public.allowance_posts enable row level security;

-- 3. CHED Form 3 reports released to the LGU. `rows` is a frozen copy taken
--    at release time, so later changes in the system never change what the
--    LGU sees. Withdrawn reports are hidden from the LGU but kept.
create table if not exists public.lgu_reports (
  id bigint generated by default as identity primary key,
  reference_number text not null,
  form_date date not null,
  rows jsonb not null,
  row_count integer not null,
  released_by text not null,
  released_at timestamptz not null default now(),
  withdrawn_at timestamptz,
  withdrawn_by text,
  download_count integer not null default 0
);
alter table public.lgu_reports enable row level security;

-- 4. End-of-cycle archive. Nothing is deleted: archived applications leave
--    every admin list and count, and the applicant keeps read-only access.
alter table public.applications
  add column if not exists archived_at timestamptz,
  add column if not exists archived_by text,
  add column if not exists archive_cycle text;
create index if not exists applications_archived_at_idx on public.applications (archived_at);
