import { NextResponse } from 'next/server'
import { supabase } from '@/app/supabaseClient'
import { APPLICANT_COOKIE_NAME, verifyApplicantCookieValue } from '@/app/lib/applicantAuth'

// Appeals & Rescheduling request endpoint (Notifications Module).
//
// Sept 30 2026: "Appeal (Retake / Re-application)" is now a request type.
// It was left out after the Sept 13-14 ROR revision, but the progress table
// row ("Appeals and Examination Rescheduling Request Form") and the
// manuscript's Scope still include it, so Pau decided to build it. As with
// reschedules, the decision itself happens in person at the office (client
// interview, Appendix D); the system records the request and shows it to
// admins.
//
// New table, not columns on `applications` — a reschedule request is its
// own event (an applicant can plausibly submit more than one over time),
// not a profile field. RLS left off to match every other table in this
// project (applications, documents) — access is server-side only via the
// service-role client, same as everywhere else.
//
// Ad hoc SQL to run in Supabase's SQL editor (same pattern as every other
// column/table addition on this project):
//
// create table if not exists reschedule_requests (
//   id bigint generated by default as identity primary key,
//   applicant_name text not null,
//   applicant_email text,
//   request_type text not null,
//   details text,
//   status text not null default 'submitted',
//   created_at timestamptz not null default now()
// );

const ALLOWED_REQUEST_TYPES = ['Reschedule Examination (Absence)', 'Appeal (Retake / Re-application)', 'Other Concern']

// GET /api/reschedule?name=Juan+Dela+Cruz
// Returns this applicant's past requests, newest first.
//
// Sept 29 security fix: this used to (a) return anyone's requests to a
// logged-out caller by typed name, and (b) even when logged in, OR-match
// on the `name` from the URL, so an applicant could type someone else's
// name and read their requests. Now it requires a real applicant session
// and ignores the `name` param entirely (still accepted so the portal's
// existing call doesn't break). Legacy rows with no applicant_user_id are
// matched by the applicant's OWN name from their applications row, the
// same fallback /api/upload uses.
export async function GET(request) {
  try {
    const applicantCookie = request.cookies.get(APPLICANT_COOKIE_NAME)?.value
    const applicantSession = await verifyApplicantCookieValue(applicantCookie)

    if (!applicantSession) {
      return NextResponse.json({ error: 'Not signed in' }, { status: 401 })
    }

    const { data: ownApplication } = await supabase
      .from('applications')
      .select('applicant_name')
      .eq('applicant_user_id', applicantSession.id)
      .order('updated_at', { ascending: false })
      .limit(1)
      .maybeSingle()

    const ownName = ownApplication?.applicant_name?.trim()

    // Sept 30 2026: the name fallback only picks up older requests that were
    // never linked to any account (same rule as /api/upload's GET).
    let query = supabase.from('reschedule_requests').select('*')
    query = ownName
      ? query.or(`applicant_user_id.eq.${applicantSession.id},and(applicant_user_id.is.null,applicant_name.ilike."${ownName.replace(/"/g, '')}")`)
      : query.eq('applicant_user_id', applicantSession.id)

    const { data, error } = await query.order('created_at', { ascending: false })

    if (error) {
      return NextResponse.json({ error: error.message }, { status: 500 })
    }

    return NextResponse.json({ success: true, requests: data || [] })
  } catch (err) {
    return NextResponse.json({ error: err.message }, { status: 500 })
  }
}

// POST /api/reschedule
// body: { applicantName, applicantEmail, requestType, details }
export async function POST(request) {
  try {
    const body = await request.json()
    const applicantName = (body.applicantName || '').trim()
    const applicantEmail = (body.applicantEmail || '').trim()
    const requestType = (body.requestType || '').trim()
    const details = (body.details || '').trim()

    if (!applicantName) {
      return NextResponse.json({ error: 'Missing applicant name' }, { status: 400 })
    }
    if (!ALLOWED_REQUEST_TYPES.includes(requestType)) {
      return NextResponse.json({ error: 'Invalid request type' }, { status: 400 })
    }
    if (!details) {
      return NextResponse.json({ error: 'Missing details' }, { status: 400 })
    }

    const applicantCookie = request.cookies.get(APPLICANT_COOKIE_NAME)?.value
    const applicantSession = await verifyApplicantCookieValue(applicantCookie)

    // Sept 29: same fix as GET. The portal is login-only, so a request
    // with no session can only come from outside the app.
    if (!applicantSession) {
      return NextResponse.json({ error: 'Not signed in' }, { status: 401 })
    }

    // Oct 1 2026: attach this applicant's newest Supporting Document that was
    // uploaded after their previous request and isn't attached to one yet
    // (Appendix J V.g), so an old file from an earlier concern is never
    // reused. Optional: a request without one still goes through.
    let supportingDocumentPath = null
    try {
      const [{ data: docs }, { data: used }] = await Promise.all([
        supabase
          .from('documents')
          .select('file_path, created_at')
          .eq('applicant_user_id', applicantSession.id)
          .eq('document_type', 'supportdoc')
          .order('created_at', { ascending: false })
          .limit(10),
        supabase
          .from('reschedule_requests')
          .select('*')
          .eq('applicant_user_id', applicantSession.id),
      ])
      const usedPaths = new Set((used || []).map((r) => r.supporting_document_path).filter(Boolean))
      const lastRequestAt = (used || []).reduce((max, r) => (r.created_at > max ? r.created_at : max), '')
      supportingDocumentPath =
        (docs || []).find((d) => !usedPaths.has(d.file_path) && (!lastRequestAt || d.created_at > lastRequestAt))?.file_path || null
    } catch (attachErr) {
      console.error('Finding the supporting document failed (continuing without):', attachErr)
    }

    const row = {
      applicant_name: applicantName,
      applicant_email: applicantSession.email || applicantEmail || null,
      applicant_user_id: applicantSession.id,
      request_type: requestType,
      details,
      status: 'submitted',
    }
    let { data, error } = await supabase
      .from('reschedule_requests')
      .insert([{ ...row, supporting_document_path: supportingDocumentPath }])
      .select()
      .single()
    // If the migration hasn't been run yet, still save the request.
    if (error && /supporting_document_path/.test(error.message || '')) {
      ;({ data, error } = await supabase.from('reschedule_requests').insert([row]).select().single())
    }

    if (error) {
      return NextResponse.json({ error: error.message }, { status: 500 })
    }

    return NextResponse.json({ success: true, request: data })
  } catch (err) {
    return NextResponse.json({ error: err.message }, { status: 500 })
  }
}